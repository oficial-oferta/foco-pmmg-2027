'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const js=fs.readFileSync('topic-catalog.js','utf8'),basic=require('./content_v4.cjs').build().questions,extra=JSON.parse(fs.readFileSync('data/topic-extras-v1.json','utf8'));
const global={window:{}};
vm.runInNewContext(js,global);
const T=global.window.FOCO_TOPICS;
assert(T,'taxonomy module did not initialize');
const all=[...basic,...extra],names=new Set(all.map(q=>q.id));
assert.equal(basic.length,2500);
assert.equal(extra.length,73);
assert.equal(names.size,all.length,'duplicate question ids');
assert.equal(extra.filter(q=>q.subject==='Português').length,57);
assert.equal(extra.filter(q=>q.subject==='Direito e Direitos Humanos').length,16);
for(const q of extra){
 assert.equal(q.options.length,4,q.id);
 assert.equal(new Set(q.options).size,4,q.id);
 assert(Number.isInteger(q.answer)&&q.answer>=0&&q.answer<4,q.id);
 assert(q.stem.length>=15&&q.explanation.length>=25,q.id);
 assert.equal(q.origin,'autoral');
 assert(!basic.some(b=>b.subject===q.subject&&T.norm(b.stem)===T.norm(q.stem)),'Repeated existing stem '+q.id);
}
const subjects=['Português','Direito e Direitos Humanos','Raciocínio Lógico-Matemático','Inglês','Literatura'];
for(const s of subjects){
 const cats=T.catalog(all,s),total=cats.reduce((a,c)=>a+c.count,0);
 assert.equal(total,all.filter(q=>q.subject===s).length,'Wrong category total: '+s);
 assert(cats.every(c=>c.count>0&&c.topics.length>0),'Empty category: '+s);
 for(const c of cats)assert(T.labels[s].includes(c.area),'Unexpected category: '+c.area);
}
const fon=T.catalog(all,'Português').find(c=>c.area==='Fonologia');
assert(fon&&fon.count>=57,'Fonologia should contain at least 57 questions');
assert(fon.topics.length>=5,'Phonology subtopics should cover main topics');
const admin=T.catalog(all,'Direito e Direitos Humanos').find(c=>c.area==='Direito Administrativo');
assert(admin&&admin.count>=16,'Administrative Law training not found');
const consti=T.catalog(all,'Direito e Direitos Humanos').find(c=>c.area==='Direito Constitucional');
assert(consti?.count>200,'Constitutional training not found');
const example={subject:'Português',topic:'Fonologia — Encontros vocálicos'};
assert.equal(T.areaFor(example),'Fonologia');
assert.equal(T.areaFor({subject:'Direito e Direitos Humanos',topic:'CF/88 — Princípios da administração pública'}),'Direito Administrativo');
assert.equal(T.areaFor({subject:'Direito e Direitos Humanos',topic:'CF/88 — Inviolabilidade do domicílio'}),'Direito Constitucional');
const s=fs.readFileSync('app.js','utf8').replace(/bootstrap\(\);\s*$/,'');
new vm.Script(s,{filename:'app.js'});
const appNode={innerHTML:'',querySelector(){return null}};
const document={querySelector(sel){return sel==='#app'?appNode:null},querySelectorAll(){return []},addEventListener(){},title:''};
const storage={getItem(){return null},setItem(){},removeItem(){}};
const v2={animate(){},home(){return ''}};
const win={FOCO_CONFIG:{},FOCO_TOPICS:T,FOCO_V2:v2,FOCO_PLAN:{DEFAULT:[180,180,180,180,180,300,300]},FOCO_EXAMS:[],scrollTo(){}};
const build=new Function('window','document','localStorage','sessionStorage','navigator','location','crypto','fetch','setInterval','clearInterval','console',s+'\nreturn {state,render,generateQueue,setSelection(value){selection=value},switchScreen};');
const env=build(win,document,storage,storage,{}, {protocol:'https:'},{randomUUID(){return 'test-uuid'}},async()=>{},()=>0,()=>{},{warn(){},error(){},log(){}});
env.state.demo=true;env.state.user={id:'demo',app_metadata:{role:'student'}};env.state.profile={display_name:'Aluno',onboarded:true};
env.state.questions=all;env.state.attempts=[];env.state.catalogSubject='Português';env.state.screen='catalog';env.render();
assert(appNode.innerHTML.includes('Fonologia')&&appNode.innerHTML.includes('catalog-topic:')&&appNode.innerHTML.includes('57 questões'),'Catalog screen not rendered');
env.setSelection({total:10,subject:'Português',topic:'Fonologia — Dígrafos',mode:'novas'});
const direct=env.generateQueue();
assert(direct.length>0&&direct.every(q=>q.subject==='Português'&&q.topic==='Fonologia — Dígrafos'),'Topic practice leaked unrelated questions');
env.setSelection({total:10,subject:'Português',area:'Fonologia',mode:'novas'});
const area=env.generateQueue();
assert(area.length===10&&area.every(q=>T.areaFor(q)==='Fonologia'),'Area practice is not focused');
env.setSelection({total:10,subject:'Todas as matérias',mode:'inteligente'});
const mixed=env.generateQueue(),tallies=Object.fromEntries(subjects.map(x=>[x,mixed.filter(q=>q.subject===x).length]));
assert.equal(mixed.length,10);
assert.equal(tallies['Português'],4);
assert.equal(tallies['Direito e Direitos Humanos'],2);
assert.equal(tallies['Raciocínio Lógico-Matemático'],2);
assert.equal(tallies['Inglês'],1);
assert.equal(tallies['Literatura'],1);
console.log('PASS: 2573 questions; 73 new; all subjects and real topics; phonology and administrative; direct practice; daily mix unchanged');
